/**
 * Check if an email domain is a disposable/temporary email service
 * @param email - The email address to check
 * @returns true if the domain is disposable, false otherwise
 */
export function isDisposableEmail(email: string): boolean {
  const domain = email.toLowerCase().split('@')[1];
  if (!domain) return false;
  return DISPOSABLE_EMAIL_DOMAINS.has(domain);
}

/**
 * Get the list of blocked domains (for debugging/admin purposes)
 */
export function getBlockedDomains(): string[] {
  return Array.from(DISPOSABLE_EMAIL_DOMAINS);
}
